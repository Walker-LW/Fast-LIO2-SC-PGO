#pragma once
#include <ros/ros.h>
#include <cmath>
#include <stdexcept>
// Startup-only configuration. Defaults preserve the imported backend.
struct BackendParameters {
    double sc_voxel_size = 0.4;
    double icp_voxel_size = 0.4;
    int icp_submap_half_frames = 25;
    double icp_max_correspondence_distance = 150.0;
    int icp_max_iterations = 100;
    double icp_transformation_epsilon = 1e-06;
    double icp_fitness_epsilon = 1e-06;
    int icp_ransac_iterations = 0;
    double icp_fitness_threshold = 0.3;
    int transform_threads = 8;
    double sc_lidar_height = 2.0;
    int sc_num_rings = 20;
    int sc_num_sectors = 60;
    int sc_exclude_recent = 30;
    int sc_candidates = 3;
    int sc_tree_period = 30;
    int sc_tree_leaf_size = 10;
    double sc_search_ratio = 0.1;
    double isam_relinearize_threshold = 0.01;
    int isam_relinearize_skip = 1;
    double prior_variance = 1e-12;
    double odom_rotation_variance = 1e-06;
    double odom_translation_variance = 0.0001;
    double loop_variance = 0.5;
    double loop_cauchy_scale = 1.0;
    double gps_xy_variance = 1000000000.0;
    double gps_z_variance = 250.0;
    double gps_cauchy_scale = 1.0;
    double loop_frequency = 1.0;
    double isam_frequency = 1.0;
    double path_frequency = 10.0;
    double map_frequency = 0.1;
    int map_skip_frames = 2;
    int subscriber_queue_size = 100;
    int publisher_queue_size = 100;
    int icp_backlog_warning = 30;
    int worker_sleep_ms = 2;
    int pose_log_interval = 100;
    void load(ros::NodeHandle& nh) {
        nh.param<double>("sc_voxel_size", sc_voxel_size, 0.4);
        if (!std::isfinite(double(sc_voxel_size)) || !(sc_voxel_size > 0)) throw std::invalid_argument("Invalid sc_voxel_size");
        ROS_INFO_STREAM("backend parameter sc_voxel_size=" << sc_voxel_size);
        nh.param<double>("icp_voxel_size", icp_voxel_size, 0.4);
        if (!std::isfinite(double(icp_voxel_size)) || !(icp_voxel_size > 0)) throw std::invalid_argument("Invalid icp_voxel_size");
        ROS_INFO_STREAM("backend parameter icp_voxel_size=" << icp_voxel_size);
        nh.param<int>("icp_submap_half_frames", icp_submap_half_frames, 25);
        if (!std::isfinite(double(icp_submap_half_frames)) || !(icp_submap_half_frames >= 0)) throw std::invalid_argument("Invalid icp_submap_half_frames");
        ROS_INFO_STREAM("backend parameter icp_submap_half_frames=" << icp_submap_half_frames);
        nh.param<double>("icp_max_correspondence_distance", icp_max_correspondence_distance, 150.0);
        if (!std::isfinite(double(icp_max_correspondence_distance)) || !(icp_max_correspondence_distance > 0)) throw std::invalid_argument("Invalid icp_max_correspondence_distance");
        ROS_INFO_STREAM("backend parameter icp_max_correspondence_distance=" << icp_max_correspondence_distance);
        nh.param<int>("icp_max_iterations", icp_max_iterations, 100);
        if (!std::isfinite(double(icp_max_iterations)) || !(icp_max_iterations > 0)) throw std::invalid_argument("Invalid icp_max_iterations");
        ROS_INFO_STREAM("backend parameter icp_max_iterations=" << icp_max_iterations);
        nh.param<double>("icp_transformation_epsilon", icp_transformation_epsilon, 1e-06);
        if (!std::isfinite(double(icp_transformation_epsilon)) || !(icp_transformation_epsilon > 0)) throw std::invalid_argument("Invalid icp_transformation_epsilon");
        ROS_INFO_STREAM("backend parameter icp_transformation_epsilon=" << icp_transformation_epsilon);
        nh.param<double>("icp_fitness_epsilon", icp_fitness_epsilon, 1e-06);
        if (!std::isfinite(double(icp_fitness_epsilon)) || !(icp_fitness_epsilon > 0)) throw std::invalid_argument("Invalid icp_fitness_epsilon");
        ROS_INFO_STREAM("backend parameter icp_fitness_epsilon=" << icp_fitness_epsilon);
        nh.param<int>("icp_ransac_iterations", icp_ransac_iterations, 0);
        if (!std::isfinite(double(icp_ransac_iterations)) || !(icp_ransac_iterations >= 0)) throw std::invalid_argument("Invalid icp_ransac_iterations");
        ROS_INFO_STREAM("backend parameter icp_ransac_iterations=" << icp_ransac_iterations);
        nh.param<double>("icp_fitness_threshold", icp_fitness_threshold, 0.3);
        if (!std::isfinite(double(icp_fitness_threshold)) || !(icp_fitness_threshold > 0)) throw std::invalid_argument("Invalid icp_fitness_threshold");
        ROS_INFO_STREAM("backend parameter icp_fitness_threshold=" << icp_fitness_threshold);
        nh.param<int>("transform_threads", transform_threads, 8);
        if (!std::isfinite(double(transform_threads)) || !(transform_threads > 0)) throw std::invalid_argument("Invalid transform_threads");
        ROS_INFO_STREAM("backend parameter transform_threads=" << transform_threads);
        nh.param<double>("sc_lidar_height", sc_lidar_height, 2.0);
        if (!std::isfinite(double(sc_lidar_height)) || !(true)) throw std::invalid_argument("Invalid sc_lidar_height");
        ROS_INFO_STREAM("backend parameter sc_lidar_height=" << sc_lidar_height);
        nh.param<int>("sc_num_rings", sc_num_rings, 20);
        if (!std::isfinite(double(sc_num_rings)) || !(sc_num_rings > 0)) throw std::invalid_argument("Invalid sc_num_rings");
        ROS_INFO_STREAM("backend parameter sc_num_rings=" << sc_num_rings);
        nh.param<int>("sc_num_sectors", sc_num_sectors, 60);
        if (!std::isfinite(double(sc_num_sectors)) || !(sc_num_sectors > 0)) throw std::invalid_argument("Invalid sc_num_sectors");
        ROS_INFO_STREAM("backend parameter sc_num_sectors=" << sc_num_sectors);
        nh.param<int>("sc_exclude_recent", sc_exclude_recent, 30);
        if (!std::isfinite(double(sc_exclude_recent)) || !(sc_exclude_recent >= 0)) throw std::invalid_argument("Invalid sc_exclude_recent");
        ROS_INFO_STREAM("backend parameter sc_exclude_recent=" << sc_exclude_recent);
        nh.param<int>("sc_candidates", sc_candidates, 3);
        if (!std::isfinite(double(sc_candidates)) || !(sc_candidates > 0)) throw std::invalid_argument("Invalid sc_candidates");
        ROS_INFO_STREAM("backend parameter sc_candidates=" << sc_candidates);
        nh.param<int>("sc_tree_period", sc_tree_period, 30);
        if (!std::isfinite(double(sc_tree_period)) || !(sc_tree_period > 0)) throw std::invalid_argument("Invalid sc_tree_period");
        ROS_INFO_STREAM("backend parameter sc_tree_period=" << sc_tree_period);
        nh.param<int>("sc_tree_leaf_size", sc_tree_leaf_size, 10);
        if (!std::isfinite(double(sc_tree_leaf_size)) || !(sc_tree_leaf_size > 0)) throw std::invalid_argument("Invalid sc_tree_leaf_size");
        ROS_INFO_STREAM("backend parameter sc_tree_leaf_size=" << sc_tree_leaf_size);
        nh.param<double>("sc_search_ratio", sc_search_ratio, 0.1);
        if (!std::isfinite(double(sc_search_ratio)) || !(sc_search_ratio > 0 && sc_search_ratio <= 1)) throw std::invalid_argument("Invalid sc_search_ratio");
        ROS_INFO_STREAM("backend parameter sc_search_ratio=" << sc_search_ratio);
        nh.param<double>("isam_relinearize_threshold", isam_relinearize_threshold, 0.01);
        if (!std::isfinite(double(isam_relinearize_threshold)) || !(isam_relinearize_threshold > 0)) throw std::invalid_argument("Invalid isam_relinearize_threshold");
        ROS_INFO_STREAM("backend parameter isam_relinearize_threshold=" << isam_relinearize_threshold);
        nh.param<int>("isam_relinearize_skip", isam_relinearize_skip, 1);
        if (!std::isfinite(double(isam_relinearize_skip)) || !(isam_relinearize_skip > 0)) throw std::invalid_argument("Invalid isam_relinearize_skip");
        ROS_INFO_STREAM("backend parameter isam_relinearize_skip=" << isam_relinearize_skip);
        nh.param<double>("prior_variance", prior_variance, 1e-12);
        if (!std::isfinite(double(prior_variance)) || !(prior_variance > 0)) throw std::invalid_argument("Invalid prior_variance");
        ROS_INFO_STREAM("backend parameter prior_variance=" << prior_variance);
        nh.param<double>("odom_rotation_variance", odom_rotation_variance, 1e-06);
        if (!std::isfinite(double(odom_rotation_variance)) || !(odom_rotation_variance > 0)) throw std::invalid_argument("Invalid odom_rotation_variance");
        ROS_INFO_STREAM("backend parameter odom_rotation_variance=" << odom_rotation_variance);
        nh.param<double>("odom_translation_variance", odom_translation_variance, 0.0001);
        if (!std::isfinite(double(odom_translation_variance)) || !(odom_translation_variance > 0)) throw std::invalid_argument("Invalid odom_translation_variance");
        ROS_INFO_STREAM("backend parameter odom_translation_variance=" << odom_translation_variance);
        nh.param<double>("loop_variance", loop_variance, 0.5);
        if (!std::isfinite(double(loop_variance)) || !(loop_variance > 0)) throw std::invalid_argument("Invalid loop_variance");
        ROS_INFO_STREAM("backend parameter loop_variance=" << loop_variance);
        nh.param<double>("loop_cauchy_scale", loop_cauchy_scale, 1.0);
        if (!std::isfinite(double(loop_cauchy_scale)) || !(loop_cauchy_scale > 0)) throw std::invalid_argument("Invalid loop_cauchy_scale");
        ROS_INFO_STREAM("backend parameter loop_cauchy_scale=" << loop_cauchy_scale);
        nh.param<double>("gps_xy_variance", gps_xy_variance, 1000000000.0);
        if (!std::isfinite(double(gps_xy_variance)) || !(gps_xy_variance > 0)) throw std::invalid_argument("Invalid gps_xy_variance");
        ROS_INFO_STREAM("backend parameter gps_xy_variance=" << gps_xy_variance);
        nh.param<double>("gps_z_variance", gps_z_variance, 250.0);
        if (!std::isfinite(double(gps_z_variance)) || !(gps_z_variance > 0)) throw std::invalid_argument("Invalid gps_z_variance");
        ROS_INFO_STREAM("backend parameter gps_z_variance=" << gps_z_variance);
        nh.param<double>("gps_cauchy_scale", gps_cauchy_scale, 1.0);
        if (!std::isfinite(double(gps_cauchy_scale)) || !(gps_cauchy_scale > 0)) throw std::invalid_argument("Invalid gps_cauchy_scale");
        ROS_INFO_STREAM("backend parameter gps_cauchy_scale=" << gps_cauchy_scale);
        nh.param<double>("loop_frequency", loop_frequency, 1.0);
        if (!std::isfinite(double(loop_frequency)) || !(loop_frequency > 0)) throw std::invalid_argument("Invalid loop_frequency");
        ROS_INFO_STREAM("backend parameter loop_frequency=" << loop_frequency);
        nh.param<double>("isam_frequency", isam_frequency, 1.0);
        if (!std::isfinite(double(isam_frequency)) || !(isam_frequency > 0)) throw std::invalid_argument("Invalid isam_frequency");
        ROS_INFO_STREAM("backend parameter isam_frequency=" << isam_frequency);
        nh.param<double>("path_frequency", path_frequency, 10.0);
        if (!std::isfinite(double(path_frequency)) || !(path_frequency > 0)) throw std::invalid_argument("Invalid path_frequency");
        ROS_INFO_STREAM("backend parameter path_frequency=" << path_frequency);
        nh.param<double>("map_frequency", map_frequency, 0.1);
        if (!std::isfinite(double(map_frequency)) || !(map_frequency > 0)) throw std::invalid_argument("Invalid map_frequency");
        ROS_INFO_STREAM("backend parameter map_frequency=" << map_frequency);
        nh.param<int>("map_skip_frames", map_skip_frames, 2);
        if (!std::isfinite(double(map_skip_frames)) || !(map_skip_frames > 0)) throw std::invalid_argument("Invalid map_skip_frames");
        ROS_INFO_STREAM("backend parameter map_skip_frames=" << map_skip_frames);
        nh.param<int>("subscriber_queue_size", subscriber_queue_size, 100);
        if (!std::isfinite(double(subscriber_queue_size)) || !(subscriber_queue_size > 0)) throw std::invalid_argument("Invalid subscriber_queue_size");
        ROS_INFO_STREAM("backend parameter subscriber_queue_size=" << subscriber_queue_size);
        nh.param<int>("publisher_queue_size", publisher_queue_size, 100);
        if (!std::isfinite(double(publisher_queue_size)) || !(publisher_queue_size > 0)) throw std::invalid_argument("Invalid publisher_queue_size");
        ROS_INFO_STREAM("backend parameter publisher_queue_size=" << publisher_queue_size);
        nh.param<int>("icp_backlog_warning", icp_backlog_warning, 30);
        if (!std::isfinite(double(icp_backlog_warning)) || !(icp_backlog_warning > 0)) throw std::invalid_argument("Invalid icp_backlog_warning");
        ROS_INFO_STREAM("backend parameter icp_backlog_warning=" << icp_backlog_warning);
        nh.param<int>("worker_sleep_ms", worker_sleep_ms, 2);
        if (!std::isfinite(double(worker_sleep_ms)) || !(worker_sleep_ms > 0)) throw std::invalid_argument("Invalid worker_sleep_ms");
        ROS_INFO_STREAM("backend parameter worker_sleep_ms=" << worker_sleep_ms);
        nh.param<int>("pose_log_interval", pose_log_interval, 100);
        if (!std::isfinite(double(pose_log_interval)) || !(pose_log_interval > 0)) throw std::invalid_argument("Invalid pose_log_interval");
        ROS_INFO_STREAM("backend parameter pose_log_interval=" << pose_log_interval);
    }
};
